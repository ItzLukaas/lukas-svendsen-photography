const ROLE_MAP: Record<string, string> = {
  Fotograf: "Photographer",
  Sportsfotograf: "Sports photographer",
  Eventfotograf: "Event photographer",
  Videograf: "Videographer",
};

/** Translate image alt text for the active locale. Danish alts pass through unchanged. */
export function localizeImageAlt(alt: string, locale: Locale): string {
  if (locale !== "en" || !alt) return alt;

  let result = alt;
  for (const [pattern, replacement] of ALT_PHRASES) {
    result = result.replace(pattern, replacement);
  }

  // Clean doubled spaces from replacements
  return result.replace(/\s{2,}/g, " ").trim();
}

export function localizeRole(role: string | undefined, locale: Locale): string | undefined {
  if (!role) return role;
  if (locale !== "en") return role;
  return ROLE_MAP[role] ?? role;
}
